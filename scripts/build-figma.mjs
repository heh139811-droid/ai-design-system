import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const read=file=>readFile(path.join(root,file),'utf8');
const tokens=JSON.parse(await read('tokens/brand.json'));
const {version}=JSON.parse(await read('package.json'));
const kit={version,tokens};
const files={
  'manifest.json':JSON.stringify({name:'원정대 기본 라이브러리 생성',api:'1.0.0',main:'code.js',editorType:['figma'],documentAccess:'dynamic-page',networkAccess:{allowedDomains:['none']}},null,2)+'\n',
  'code.js':`// Generated by npm run build. Do not edit.\nconst KIT = ${JSON.stringify(kit)};\n`+await read('src/figma-kit.js'),
  'README.md':await read('docs/FIGMA.md'),
  'tokens.json':JSON.stringify(tokens,null,2)+'\n'
};
await mkdir(path.join(root,'dist/figma'),{recursive:true});
for(const [name,value] of Object.entries(files)) {
  if(process.argv.includes('--check')) {
    if(await read(`dist/figma/${name}`)!==value)throw new Error(`dist/figma/${name} is stale; run npm run build`);
  }else await writeFile(path.join(root,'dist/figma',name),value);
}
console.log(process.argv.includes('--check')?'Figma kit is current.':'Built Figma library generator.');
